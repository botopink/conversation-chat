#!/usr/bin/env bash
# status.sh — writes status.md: per conversation, the messages, the last one, who has not read what, and the
# questions still without an answer. Run before every commit (README § Rules); never edited by hand.
set -euo pipefail
cd "$(dirname "$0")/.."
out="status.md"
field() { sed -n "s/^$2: *//p" "$1" | head -1 | sed 's/ *#.*$//'; }
{
    echo "# Status — the conversation at a glance"
    echo
    echo "Generated by \`scripts/status.sh\` on $(date -u +%Y-%m-%d\ %H:%M) UTC; never edited by hand."
    echo
    echo "## Who owes a read"
    echo
    for side in maintainer machine-1 machine-2 machine-3; do
        n="$(scripts/unread.sh "$side" 2>/dev/null | grep -c '^  ' || true)"
        if [ "$n" -gt 0 ]; then
            echo "- **$side**: $n unread — \`scripts/unread.sh $side\`"
        else
            echo "- $side: nothing unread"
        fi
    done
    echo
    echo "## Conversations"
    echo
    echo "| Conversation | Messages | Last message | From | Subject | Read |"
    echo "|---|---|---|---|---|---|"
    for d in machine-1 machine-2 machine-3 all; do
        files="$(ls "$d"/????????-????-*.md 2>/dev/null | sort || true)"
        if [ -z "$files" ]; then echo "| \`$d/\` | 0 | — | — | — | — |"; continue; fi
        count="$(printf '%s\n' "$files" | wc -l)"
        last="$(printf '%s\n' "$files" | tail -1)"
        echo "| \`$d/\` | $count | \`${last#*/}\` | $(field "$last" from) | $(field "$last" subject) | $(field "$last" read) |"
    done
    echo
    echo "## Questions without an answer"
    echo
    any=0
    for f in $(ls machine-*/????????-????-*.md all/????????-????-*.md 2>/dev/null | sort -t/ -k2); do
        [ "$(field "$f" purpose)" = question ] || continue
        if ! grep -lq "^in-reply-to: *$f" machine-*/*.md all/*.md 2>/dev/null; then
            any=1; echo "- \`$f\` — from $(field "$f" from) to $(field "$f" to): $(field "$f" subject)"
        fi
    done
    [ "$any" -eq 0 ] && echo "None."
    echo
    echo "## Every message, newest first"
    echo
    echo "| When | Id | From → to | Purpose | Subject | Read |"
    echo "|---|---|---|---|---|---|"
    for f in $(ls machine-*/????????-????-*.md all/????????-????-*.md 2>/dev/null | sort -t/ -k2 -r); do
        b="${f#*/}"; when="${b:0:4}-${b:4:2}-${b:6:2} ${b:9:2}:${b:11:2}"; id="$(printf '%s' "$b" | sed -E 's/.*-(m[123t]-[0-9]+)\.md$/\1/')"
        echo "| $when | \`$id\` | $(field "$f" from) → $(field "$f" to) | $(field "$f" purpose) | $(field "$f" subject) | $(field "$f" read) |"
    done
} > "$out"
echo "status.md written"
